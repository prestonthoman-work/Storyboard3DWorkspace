import Foundation
import RealityKit

/// What Claude returns for a prompt: an object as a list of simple shapes, sized in
/// real-world centimeters. Matches `ClaudeModelGenerationService.schema`.
nonisolated struct ObjectDesign: Codable, Equatable {
    var name: String
    var parts: [Part]

    struct Part: Codable, Equatable {
        var label: String
        var shape: String
        var widthCm: Double
        var heightCm: Double
        var depthCm: Double
        var xCm: Double
        var zCm: Double
        var bottomCm: Double
        var orientation: String
        var yawDegrees: Double
        var color: String
        var isMainBody: Bool
    }

    /// The design's parts at real-world size, in centimeters, before fitting to the set.
    var unfittedParts: [GeneratedPart] {
        parts.map { part in
            GeneratedPart(shape: GeneratedPart.Shape(rawValue: part.shape) ?? .box,
                          center: SIMD3(Float(part.xCm), Float(part.bottomCm + part.heightCm / 2), Float(part.zCm)),
                          size: SIMD3(Float(part.widthCm), Float(part.heightCm), Float(part.depthCm)),
                          orientation: GeneratedPart.Orientation(rawValue: part.orientation) ?? .upright,
                          color: part.color,
                          isMainBody: part.isMainBody,
                          yaw: part.yawDegrees == 0 ? nil : Float(part.yawDegrees) * .pi / 180)
        }
    }
}

/// Generates objects with Claude: Claude designs the object from simple shapes, which are
/// built in the same low-poly style as the built-in objects. People still become built-in
/// poseable characters, prompts that just name a built-in object ("a red house") use it, and
/// bases use the built-in templates.
///
/// Without an API key, prompts are matched like sample mode. With one, a failed request
/// throws its reason (a bad key, no credit, a timeout) instead of placing a stand-in, so the
/// person sees what went wrong and can try again.
struct ClaudeModelGenerationService: ModelGenerationService {
    typealias Designer = (_ prompt: String, _ apiKey: String) async throws -> ObjectDesign

    static let serviceName = "Claude"

    let apiKey: () -> String?
    let design: Designer
    private let sample = SampleModelGenerationService()

    init(apiKey: @escaping () -> String? = { ClaudeAPIKey.current },
         design: @escaping Designer = { try await ClaudeClient().design(prompt: $0, apiKey: $1) }) {
        self.apiKey = apiKey
        self.design = design
    }

    var source: ModelSource {
        apiKey() == nil ? .sample : .service(name: Self.serviceName)
    }

    func generateObject(prompt: String) async throws -> GeneratedModel {
        if let builtIn = sample.builtInModel(for: prompt) { return builtIn }
        guard let key = apiKey() else {
            return try await fallback(prompt: prompt, reason: "Add a Claude API key to generate objects.")
        }

        let parts: [GeneratedPart]
        let name: String
        do {
            let design = try await design(prompt, key)
            parts = GeneratedObjectBuilder.fit(design.unfittedParts)
            name = Self.cleanName(design.name, prompt: prompt)
        } catch let failure as ClaudeClient.Failure {
            throw failure
        } catch {
            throw ClaudeClient.Failure(message: "Couldn't reach Claude. Check your internet connection.")
        }
        guard !parts.isEmpty else {
            throw ClaudeClient.Failure(message: "Claude didn't return any shapes for that. Try describing it differently.")
        }

        return GeneratedModel(
            displayName: name,
            source: .service(name: Self.serviceName),
            recipe: .generatedObject(name: name, parts: parts, color: nil),
            entity: GeneratedObjectBuilder.make(name: name, parts: parts, tint: nil),
            note: "Generated by Claude from \(parts.count) shapes. Generate again for a different take."
        )
    }

    func generateBase(prompt: String) async throws -> GeneratedModel {
        try await sample.generateBase(prompt: prompt)
    }

    private func fallback(prompt: String, reason: String) async throws -> GeneratedModel {
        let model = try await sample.generateObject(prompt: prompt)
        return GeneratedModel(displayName: model.displayName, source: model.source, recipe: model.recipe,
                              entity: model.entity, note: [reason, model.note].compactMap { $0 }.joined(separator: " "))
    }

    /// The model's name, without color words (recoloring adds its own), or the prompt's.
    static func cleanName(_ name: String, prompt: String) -> String {
        let colors = Set(SampleObjectCatalog.colorNames + ["grey"])
        let words = name.split(separator: " ").filter { !colors.contains($0.lowercased()) }
        let cleaned = words.joined(separator: " ").trimmingCharacters(in: .whitespacesAndNewlines)
        if !cleaned.isEmpty, cleaned.count <= 40 { return cleaned }
        let fallback = prompt.split(separator: " ").prefix(4).joined(separator: " ")
        return fallback.prefix(1).uppercased() + fallback.dropFirst()
    }

    // MARK: Prompt and schema

    static let instructions = """
        You design 3D models for a miniature film set (a storyboarding tool). Each model is built \
        only from simple shapes: box, roundedBox, sphere, cylinder, cone and wedge. The app shrinks \
        it to the scale of its figures, so use realistic real-world sizes in centimeters.

        Coordinates: x runs left (negative) to right (positive); z runs back (negative) to front \
        (positive). The object's front faces +z and its middle is at x 0, z 0. bottomCm is the \
        height of the part's lowest point above the ground: 0 for parts on the ground, and a part \
        sitting on another starts at that part's bottomCm plus its heightCm.

        Sizes: widthCm, heightCm and depthCm are the part's full size along x, y and z before any \
        yaw. A sphere, cylinder or cone fills that box, so equal width and depth make it round.

        orientation (for cylinders and cones): upright stands the axis vertically with a cone's tip \
        up; upsideDown points a cone's tip down (lamp shades, funnels); alongX lays the axis left to \
        right; alongZ lays it front to back. Car wheels on a car facing +x are cylinders alongZ; \
        give their size as the final box (diameter as width and height, tire thickness as depth).
        wedge is a triangular prism, like a gable roof: flat bottom, ridge along x at the top, \
        sloping toward front and back. Use yawDegrees 90 to run the ridge front to back.
        yawDegrees turns the part around the vertical axis, counterclockwise seen from above. \
        Use 0 for most parts.

        Make the object recognizable at a glance, like a well-made model-railway miniature: get \
        the proportions and silhouette right first, then add a few telling details (windows, \
        handles, trim). Use about 6 to 30 parts. Parts must touch or overlap so the object is one \
        connected piece standing on the ground. Pick realistic colors from the list; mark the \
        parts of the main painted body (the part someone would repaint) with isMainBody. \
        The name is a short Title Case name without colors, like "Park Bench".
        """

    static var schema: [String: Any] {
        let number: [String: Any] = ["type": "number"]
        let part: [String: Any] = [
            "type": "object",
            "properties": [
                "label": ["type": "string", "description": "What the part is, like \"seat\" or \"front left leg\""],
                "shape": ["type": "string", "enum": GeneratedPart.Shape.allCases.map(\.rawValue)],
                "widthCm": number, "heightCm": number, "depthCm": number,
                "xCm": number, "zCm": number, "bottomCm": number,
                "orientation": ["type": "string", "enum": GeneratedPart.Orientation.allCases.map(\.rawValue)],
                "yawDegrees": number,
                "color": ["type": "string", "enum": GeneratedPalette.names],
                "isMainBody": ["type": "boolean"]
            ] as [String: Any],
            "required": ["label", "shape", "widthCm", "heightCm", "depthCm", "xCm", "zCm", "bottomCm",
                         "orientation", "yawDegrees", "color", "isMainBody"],
            "additionalProperties": false
        ]
        return [
            "type": "object",
            "properties": [
                "name": ["type": "string"],
                "parts": ["type": "array", "items": part]
            ] as [String: Any],
            "required": ["name", "parts"],
            "additionalProperties": false
        ]
    }
}

/// A minimal client for the Claude Messages API (there's no official Swift SDK).
struct ClaudeClient {
    static let endpoint = URL(string: "https://api.anthropic.com/v1/messages")!
    static let model = "claude-opus-5-5"

    /// A failure with a short explanation to show under the prompt.
    struct Failure: LocalizedError {
        let message: String
        var errorDescription: String? { message }
    }

    var session: URLSession = .shared

    func design(prompt: String, apiKey: String) async throws -> ObjectDesign {
        let body: [String: Any] = [
            "model": Self.model,
            "max_tokens": 16000,
            "system": ClaudeModelGenerationService.instructions,
            "messages": [["role": "user", "content": "Design this object: \(prompt)"]],
            "output_config": [
                "effort": "medium",
                "format": ["type": "json_schema", "schema": ClaudeModelGenerationService.schema]
            ] as [String: Any],
            // If a safety classifier declines, the API retries on Anthropic's recommended model.
            "fallbacks": "default"
        ]
        // The answer arrives all at once when the design is done, so allow a few minutes.
        var request = URLRequest(url: Self.endpoint, timeoutInterval: 300)
        request.httpMethod = "POST"
        request.setValue("application/json", forHTTPHeaderField: "content-type")
        request.setValue(apiKey, forHTTPHeaderField: "x-api-key")
        request.setValue("2026-10-21", forHTTPHeaderField: "anthropic-version")
        request.setValue("server-side-fallback-2026-07-01", forHTTPHeaderField: "anthropic-beta")
        request.httpBody = try JSONSerialization.data(withJSONObject: body)

        let data = try await send(request)
        return try Self.parse(data)
    }

    /// Checks a key with the free Models endpoint, so a bad key is caught when it's entered
    /// rather than on the first generation. Nil when the key works.
    func verify(apiKey: String) async -> String? {
        var request = URLRequest(url: URL(string: "https://api.anthropic.com/v1/models?limit=1")!, timeoutInterval: 20)
        request.setValue(apiKey, forHTTPHeaderField: "x-api-key")
        request.setValue("2026-10-21", forHTTPHeaderField: "anthropic-version")
        do {
            let (data, response) = try await session.data(for: request)
            let status = (response as? HTTPURLResponse)?.statusCode ?? 0
            return status == 200 ? nil : Self.message(forStatus: status, body: data)
        } catch {
            return "Couldn't reach Claude to check the key. Check your internet connection."
        }
    }

    /// Sends the request, retrying briefly when the API is busy.
    private func send(_ request: URLRequest) async throws -> Data {
        var attempt = 0
        while true {
            let data: Data, response: URLResponse
            do {
                (data, response) = try await session.data(for: request)
            } catch let error as URLError where error.code == .timedOut {
                throw Failure(message: "Claude took too long to answer.")
            } catch {
                throw Failure(message: "Couldn't reach Claude. Check your internet connection.")
            }
            let status = (response as? HTTPURLResponse)?.statusCode ?? 0
            if status == 200 { return data }

            let retryable = status == 429 || status == 500 || status == 529
            let retryAfter = (response as? HTTPURLResponse)?.value(forHTTPHeaderField: "retry-after").flatMap(Double.init)
            if retryable, attempt < 2, status != 429 || retryAfter != nil {
                attempt += 1
                let delay = min(retryAfter ?? Double(attempt) * 2, 20)
                try await Task.sleep(for: .seconds(delay))
                continue
            }
            throw Failure(message: Self.message(forStatus: status, body: data))
        }
    }

    static func message(forStatus status: Int, body: Data) -> String {
        switch status {
        case 401: return "Claude didn't accept the API key. Check it under Claude API Key in the Objects tab."
        case 402: return "The Claude account is out of credit."
        case 403: return "This API key isn't allowed to use Claude."
        case 429: return "Claude's usage limit was reached. Try again later."
        case 500, 529: return "Claude is busy right now. Try again in a moment."
        default:
            let detail = (try? JSONSerialization.jsonObject(with: body) as? [String: Any])
                .flatMap { $0["error"] as? [String: Any] }?["message"] as? String
            return "Claude couldn't generate that" + (detail.map { " (\($0))." } ?? ".")
        }
    }

    /// Reads the design from a Messages API response.
    static func parse(_ data: Data) throws -> ObjectDesign {
        struct Response: Decodable {
            struct Block: Decodable {
                let type: String
                let text: String?
            }
            let content: [Block]
            let stop_reason: String?
        }
        guard let response = try? JSONDecoder().decode(Response.self, from: data) else {
            throw Failure(message: "Claude's answer couldn't be read.")
        }
        switch response.stop_reason {
        case "refusal": throw Failure(message: "Claude wouldn't make that.")
        case "max_tokens": throw Failure(message: "That object was too complicated to finish.")
        default: break
        }
        let text = response.content.filter { $0.type == "text" }.compactMap(\.text).joined()
        guard let design = try? JSONDecoder().decode(ObjectDesign.self, from: Data(text.utf8)) else {
            throw Failure(message: "Claude's answer couldn't be read.")
        }
        return design
    }
}
