import Foundation
import RealityKit

/// Where a model came from, so the UI can be honest about sample output.
enum ModelSource: Codable, Equatable {
    case sample
    case service(name: String)
    /// A model file the person imported.
    case imported

    var label: String {
        switch self {
        case .sample: "Sample"
        case .imported: "Imported"
        case .service(let name): "Generated by \(name)"
        }
    }
}

/// Enough information to rebuild generated content later (undo, or reopening the app).
///
/// Sample mode can rebuild everything from these few values. Imported models point at the
/// model file stored in the project; a real generation service could do the same.
enum ModelRecipe: Codable, Equatable {
    case sampleObject(kind: String, color: String?)
    case placeholder(color: String?)
    case baseTemplate(String)
    /// A built-in poseable character.
    case character(kind: String, color: String?, proportions: CharacterProportions)
    /// A USDZ file the person imported, stored in the project under `fileID`. `name` is the
    /// file's name, for naming the object.
    case importedModel(fileID: UUID, name: String)
    /// An object a generation service designed from simple shapes, already fitted to the set.
    /// `color` repaints its main-body parts (nil for the colors it was generated with).
    case generatedObject(name: String, parts: [GeneratedPart], color: String?)

    /// The color name, for recipes that can be recolored.
    var colorName: String? {
        switch self {
        case .sampleObject(_, let color), .placeholder(let color), .character(_, let color, _),
             .generatedObject(_, _, let color): color
        case .baseTemplate, .importedModel: nil
        }
    }

    var canRecolor: Bool {
        switch self {
        case .sampleObject, .placeholder, .character: true
        case .generatedObject(_, let parts, _): parts.contains(where: \.isMainBody)
        case .baseTemplate, .importedModel: false
        }
    }

    /// The same content in another color (nil for its default colors).
    func recolored(_ color: String?) -> ModelRecipe {
        switch self {
        case .sampleObject(let kind, _): .sampleObject(kind: kind, color: color)
        case .placeholder: .placeholder(color: color)
        case .character(let kind, _, let proportions): .character(kind: kind, color: color, proportions: proportions)
        case .generatedObject(let name, let parts, _): .generatedObject(name: name, parts: parts, color: color)
        case .baseTemplate, .importedModel: self
        }
    }

    /// The built-in character this describes, if it is one.
    var characterKind: CharacterKind? {
        if case .character(let kind, _, _) = self { CharacterKind(rawValue: kind) } else { nil }
    }

    var characterProportions: CharacterProportions? {
        if case .character(_, _, let proportions) = self { proportions } else { nil }
    }

    /// The stored model file this is built from, for imported models.
    var importedFileID: UUID? {
        if case .importedModel(let fileID, _) = self { fileID } else { nil }
    }
}

struct GeneratedModel {
    let displayName: String
    let source: ModelSource
    let recipe: ModelRecipe
    /// Built so it's centered on the origin and rests on y = 0.
    let entity: Entity
    /// Optional explanation of what was produced, shown under the prompt field.
    let note: String?
}

/// Turns text prompts into 3D content: objects to place, and bases to place them on.
protocol ModelGenerationService {
    /// The kind of output this service produces.
    var source: ModelSource { get }

    func generateObject(prompt: String) async throws -> GeneratedModel
    func generateBase(prompt: String) async throws -> GeneratedModel
}

enum ModelGenerationServiceProvider {
    /// Objects are generated with Claude when an API key has been added, falling back to
    /// sample matching otherwise. To use another service, return a type that conforms to
    /// `ModelGenerationService` here.
    static func makeService() -> any ModelGenerationService {
        // Tests always use sample matching, so they're fast and repeatable whether or not
        // a Claude API key is set up.
        if ProcessInfo.processInfo.environment["XCTestConfigurationFilePath"] != nil {
            return SampleModelGenerationService()
        }
        return ClaudeModelGenerationService()
    }
}
