import RealityKit

/// Where the current model came from, so the UI can be honest about sample output.
enum ModelSource: Equatable {
    case sample
    case service(name: String)

    var label: String {
        switch self {
        case .sample: "Sample model"
        case .service(let name): "Generated by \(name)"
        }
    }
}

struct GeneratedModel {
    let displayName: String
    let source: ModelSource
    let entity: Entity
}

/// Turns a text prompt into a 3D model.
protocol ModelGenerationService {
    /// The kind of output this service produces.
    var source: ModelSource { get }

    func generateModel(prompt: String) async throws -> GeneratedModel
}

enum ModelGenerationServiceProvider {
    /// This project has no model-generation backend configured, so the app runs
    /// in sample mode. To connect a real service, return a type that conforms to
    /// `ModelGenerationService` here.
    static func makeService() -> any ModelGenerationService {
        SampleModelGenerationService()
    }
}
