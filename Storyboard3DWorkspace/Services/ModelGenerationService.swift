import RealityKit

/// Where a model came from, so the UI can be honest about sample output.
enum ModelSource: Codable, Equatable {
    case sample
    case service(name: String)

    var label: String {
        switch self {
        case .sample: "Sample"
        case .service(let name): "Generated by \(name)"
        }
    }
}

/// Enough information to rebuild generated content later (undo, or reopening the app).
///
/// Sample mode can rebuild everything from these few values. A real generation service
/// would add a case that points at the model file it saved, such as a USDZ on disk.
enum ModelRecipe: Codable, Equatable {
    case sampleObject(kind: String, color: String?)
    case placeholder(color: String?)
    case baseTemplate(String)
}

struct GeneratedModel {
    let displayName: String
    let source: ModelSource
    let recipe: ModelRecipe
    /// Built so it's centered on the origin and rests on y = 0.
    let entity: Entity
    /// Optional explanation of what was produced, shown under the prompt field.
    let note: String?
}

/// Turns text prompts into 3D content: objects to place, and bases to place them on.
protocol ModelGenerationService {
    /// The kind of output this service produces.
    var source: ModelSource { get }

    func generateObject(prompt: String) async throws -> GeneratedModel
    func generateBase(prompt: String) async throws -> GeneratedModel
}

enum ModelGenerationServiceProvider {
    /// This project has no AI model-generation backend configured, so the app runs in
    /// sample mode. To connect a real service, return a type that conforms to
    /// `ModelGenerationService` here.
    static func makeService() -> any ModelGenerationService {
        SampleModelGenerationService()
    }
}
